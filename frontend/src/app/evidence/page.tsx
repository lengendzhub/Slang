"use client";

import React, { useState, useEffect } from "react";
import Link from "next/link";
import { FrostedNav } from "@/components/ui/FrostedNav";
import { loadUserSession, saveUserSession, EvidenceItemState } from "@/lib/store";
import {
  ShieldCheck,
  Plus,
  GitBranch,
  FileText,
  CheckCircle2,
  Trash2,
  Edit2,
  ExternalLink,
  Search,
  UploadCloud,
  ArrowRight,
} from "lucide-react";

export default function EvidenceBankPage() {
  const [evidenceList, setEvidenceList] = useState<EvidenceItemState[]>([]);
  const [searchQuery, setSearchQuery] = useState("");
  const [showAddForm, setShowAddForm] = useState(false);
  const [newText, setNewText] = useState("");
  const [newContext, setNewContext] = useState("");
  const [newSource, setNewSource] = useState<"github" | "project_report">("github");
  const [isLoaded, setIsLoaded] = useState(false);

  useEffect(() => {
    const sync = () => {
      const session = loadUserSession();
      setEvidenceList(session.evidenceBank || []);
      setIsLoaded(true);
    };
    sync();
    window.addEventListener("slang_session_updated", sync);
    window.addEventListener("tailorai_session_updated", sync);
    return () => {
      window.removeEventListener("slang_session_updated", sync);
      window.removeEventListener("tailorai_session_updated", sync);
    };
  }, []);

  const handleDelete = (id: string) => {
    const updated = evidenceList.filter((item) => item.id !== id);
    setEvidenceList(updated);
    saveUserSession({ evidenceBank: updated });
  };

  const handleToggleVerify = (id: string) => {
    const updated = evidenceList.map((item) =>
      item.id === id ? { ...item, verified: !item.verified } : item
    );
    setEvidenceList(updated);
    saveUserSession({ evidenceBank: updated });
  };

  const handleAddEvidence = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newText.trim()) return;

    const newRecord: EvidenceItemState = {
      id: `ev_ext_${Date.now().toString().slice(-4)}`,
      source: newSource,
      sourceName: newSource === "github" ? "GitHub Repository Import" : "Project Report Import",
      text: newText.trim(),
      context: newContext.trim() || "External Candidate Proof",
      verified: true,
      dateAdded: "Just now",
    };

    const updated = [newRecord, ...evidenceList];
    setEvidenceList(updated);
    saveUserSession({ evidenceBank: updated });
    setNewText("");
    setNewContext("");
    setShowAddForm(false);
  };

  const filtered = evidenceList.filter(
    (e) =>
      e.text.toLowerCase().includes(searchQuery.toLowerCase()) ||
      e.context.toLowerCase().includes(searchQuery.toLowerCase()) ||
      e.id.toLowerCase().includes(searchQuery.toLowerCase())
  );

  return (
    <div className="min-h-screen flex flex-col bg-[var(--bg)] text-[var(--ink)]">
      <FrostedNav />

      <main className="flex-1 max-w-[1200px] w-full mx-auto px-4 sm:px-6 py-8 sm:py-10">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 pb-6 mb-8 border-b border-hairline">
          <div>
            <div className="flex items-center gap-2 mb-1">
              <span className="text-[12px] font-semibold uppercase tracking-wider text-accent">
                Evidence Bank Management
              </span>
              <span className="text-[11px] text-ink-muted">•</span>
              <span className="text-[12px] text-ink-muted">Non-Negotiable Rule #2</span>
            </div>
            <h1 className="text-[28px] md:text-[34px] font-semibold tracking-tight text-ink">
              Candidate Proof Anchors ({evidenceList.length})
            </h1>
            <p className="text-[14px] text-ink-muted">
              Every resume claim generated by Slang points to one of these immutable records.
            </p>
          </div>

          <button
            type="button"
            onClick={() => setShowAddForm(!showAddForm)}
            aria-expanded={showAddForm}
            aria-controls="add-evidence-form"
            className="min-h-[44px] px-5 py-2 rounded-pill bg-accent text-white text-[14px] font-medium hover:bg-accent-hover shadow-subtle flex items-center gap-1.5 transition-all active:scale-95 cursor-pointer"
          >
            <Plus className="w-4 h-4" />
            {showAddForm ? "Close Form" : "Add External Source"}
          </button>
        </div>

        {/* Add External Evidence Form */}
        {showAddForm && (
          <form
            id="add-evidence-form"
            onSubmit={handleAddEvidence}
            className="bg-surface rounded-card p-6 mb-8 border-2 border-accent/30 shadow-subtle"
          >
            <h3 className="text-[17px] font-semibold text-ink mb-1">
              Add Evidence Anchor (GitHub / Project Text)
            </h3>
            <p className="text-[13px] text-ink-muted mb-4">
              Add verified achievements from your older resumes, GitHub repositories, or technical whitepapers.
            </p>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-4">
              <div>
                <label htmlFor="source-type-select" className="text-[12px] font-semibold text-ink-muted uppercase block mb-1">
                  Source Type
                </label>
                <select
                  id="source-type-select"
                  value={newSource}
                  onChange={(e) => setNewSource(e.target.value as any)}
                  className="w-full min-h-[44px] p-2.5 rounded-xl border border-hairline bg-canvas text-[13px] text-ink focus:outline-none focus:ring-2 focus:ring-accent"
                >
                  <option value="github">GitHub Repo / README</option>
                  <option value="project_report">Project Report / Whitepaper</option>
                </select>
              </div>

              <div>
                <label htmlFor="project-name-input" className="text-[12px] font-semibold text-ink-muted uppercase block mb-1">
                  Project or Repo Name
                </label>
                <input
                  id="project-name-input"
                  type="text"
                  value={newContext}
                  onChange={(e) => setNewContext(e.target.value)}
                  placeholder="e.g. github.com/username/project"
                  className="w-full min-h-[44px] p-2.5 rounded-xl border border-hairline bg-canvas text-[13px] text-ink focus:outline-none focus:ring-2 focus:ring-accent"
                />
              </div>
            </div>

            <div className="mb-4">
              <label htmlFor="achievement-text-input" className="text-[12px] font-semibold text-ink-muted uppercase block mb-1">
                Verified Achievement Text
              </label>
              <textarea
                id="achievement-text-input"
                value={newText}
                onChange={(e) => setNewText(e.target.value)}
                placeholder="Paste the exact bullet or accomplishment metric..."
                className="w-full p-3 rounded-xl border border-hairline bg-canvas text-[13px] font-mono text-ink resize-none focus:outline-none focus:ring-2 focus:ring-accent leading-relaxed"
                rows={3}
              />
            </div>

            <div className="flex justify-end gap-2.5">
              <button
                type="button"
                onClick={() => setShowAddForm(false)}
                className="min-h-[44px] px-5 py-2 rounded-pill text-[13px] font-medium border border-hairline text-ink hover:bg-canvas transition-all cursor-pointer"
              >
                Cancel
              </button>
              <button
                type="submit"
                className="min-h-[44px] px-6 py-2 rounded-pill bg-accent text-white text-[13px] font-medium hover:bg-accent-hover shadow-subtle transition-all active:scale-95 cursor-pointer"
              >
                Save Evidence Anchor
              </button>
            </div>
          </form>
        )}

        {/* Empty State */}
        {isLoaded && evidenceList.length === 0 ? (
          <div className="bg-surface border border-hairline rounded-card p-12 text-center max-w-[600px] mx-auto my-12 shadow-subtle">
            <div className="w-16 h-16 rounded-full bg-accent/10 text-accent flex items-center justify-center mx-auto mb-4">
              <UploadCloud className="w-8 h-8" />
            </div>
            <h3 className="text-[20px] font-semibold text-ink mb-2">
              No evidence anchors in your bank
            </h3>
            <p className="text-[14px] text-ink-muted mb-6 max-w-[420px] mx-auto leading-relaxed">
              Upload your PDF resume in Studio to automatically index your achievements into verified Evidence Bank records.
            </p>
            <Link
              href="/workspace"
              className="min-h-[44px] px-7 py-2.5 rounded-pill bg-accent text-white text-[14px] font-medium inline-flex items-center gap-1.5 shadow-subtle hover:bg-accent-hover transition-all active:scale-95 cursor-pointer"
            >
              Upload Resume in Workspace
              <ArrowRight className="w-4 h-4" />
            </Link>
          </div>
        ) : (
          <>
            {/* Search Bar */}
            <div className="mb-6 relative">
              <Search className="w-4 h-4 text-ink-muted absolute left-4 top-1/2 -translate-y-1/2 pointer-events-none" />
              <input
                type="text"
                value={searchQuery}
                aria-label="Search evidence records by keyword, ID, or source"
                onChange={(e) => setSearchQuery(e.target.value)}
                placeholder="Search evidence records by keyword, evidence_id, or source..."
                className="w-full min-h-[44px] pl-11 pr-4 py-2.5 rounded-2xl border border-hairline bg-surface text-[14px] text-ink focus:outline-none focus:ring-2 focus:ring-accent transition-all"
              />
            </div>

            {/* Evidence List */}
            <div className="space-y-4">
              {filtered.map((ev) => (
                <div key={ev.id} className="bg-surface border border-hairline rounded-card p-5 shadow-subtle">
                  <div className="flex flex-wrap items-center justify-between pb-3 mb-3 border-b border-hairline gap-2">
                    <div className="flex items-center gap-2">
                      <span className="text-[12px] font-mono font-semibold text-accent">
                        {ev.id}
                      </span>
                      <span className="text-[11px] text-ink-muted">•</span>
                      <span className="text-[12px] text-ink-muted flex items-center gap-1.5">
                        {ev.source === "github" ? (
                          <GitBranch className="w-3.5 h-3.5 text-accent" />
                        ) : (
                          <FileText className="w-3.5 h-3.5" />
                        )}
                        {ev.sourceName}
                      </span>
                    </div>

                    <div className="flex items-center gap-2">
                      <span
                        className={`inline-flex items-center gap-1 text-[11px] font-medium px-2.5 py-0.5 rounded-pill border ${
                          ev.verified
                            ? "bg-status-supported-bg text-status-supported-text border-status-supported-text/20"
                            : "bg-amber-500/10 text-amber-600 border-amber-500/20"
                        }`}
                      >
                        <CheckCircle2 className="w-3 h-3" />
                        {ev.verified ? "User Confirmed" : "Needs Review"}
                      </span>
                    </div>
                  </div>

                  <p className="text-[14px] font-mono text-ink leading-relaxed mb-3">
                    "{ev.text}"
                  </p>

                  <div className="pt-2 flex flex-wrap items-center justify-between text-[12px] text-ink-muted gap-2">
                    <span>Context: {ev.context} • Added {ev.dateAdded}</span>

                    <div className="flex items-center gap-2">
                      <button
                        type="button"
                        onClick={() => handleToggleVerify(ev.id)}
                        aria-label={`Toggle verification status for record ${ev.id}`}
                        className="min-h-[44px] min-w-[44px] sm:min-h-0 sm:min-w-0 px-3 py-1.5 rounded-pill text-[12px] font-medium border border-hairline hover:bg-canvas hover:text-ink transition-all cursor-pointer"
                      >
                        {ev.verified ? "Mark Unverified" : "Confirm Record"}
                      </button>
                      <button
                        type="button"
                        onClick={() => handleDelete(ev.id)}
                        aria-label={`Delete evidence anchor ${ev.id}`}
                        className="min-h-[44px] min-w-[44px] sm:min-h-0 sm:min-w-0 px-3 py-1.5 rounded-pill text-[12px] font-medium border border-red-500/20 text-red-600 hover:bg-red-500/10 transition-all cursor-pointer flex items-center gap-1"
                      >
                        <Trash2 className="w-3.5 h-3.5" />
                        Delete
                      </button>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          </>
        )}
      </main>
    </div>
  );
}
